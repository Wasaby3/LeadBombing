/* Praise for the 1st, 5th and every 10th lead processed today; the generic ones name the number. */
export function milestonePhrases(n) {
  if (n === 1) return FIRST;
  if (n === 5) return FIFTH;
  const leads = `${n} ${pluralLeads(n)}`;
  return [
    `Уже ${leads} за сегодня! Горжусь тобой`,
    `${leads}! Вот это темп, старина`,
    `Ого, ${leads}! Пойду премию оформлять`,
    `${leads} — я аж колпак снимаю`,
  ];
}
