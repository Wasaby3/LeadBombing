/* The phrases for an action with its detail (count, value); empty for an unknown action. */
export function actionPhrases(action, detail = {}) {
  const rule = ACTIONS[action];
  if (!rule) return [];
  return typeof rule.phrases === 'function' ? rule.phrases(detail) : rule.phrases;
}
